export const HISTORY_MAX = 3;

// 危險徵兆字詞（#36 審查）：答案檢查、範本、症狀登記的安全提醒共用。
// 「天氣過熱」「水溫正常是多少」「方向盤重新包皮」不算。「冒煙的燒肉店」照樣算：客休室裡講冒煙多半是車子，寧可多叫一次專員。
export const DANGER = "冒.{0,2}煙|(?<!天氣|氣溫|天)過熱|水溫[^，。？?]{0,4}(?:高|飆|爬|升)|起火|著火|煞不住|煞車(?:沒力|失靈|變軟|很軟)|方向盤(?:很|變得?|超|好|有點)?重(?![新量要複])";

// 交通號誌（「停紅燈」「等紅燈」「紅燈停車」）不是儀表燈，也不算紅燈警示。「亮紅燈時好時壞」照樣算。
export const TRAFFIC_LIGHT = /[停等]紅燈|紅燈停/g;
// 危險症狀：症狀登記的安全提醒和症狀開場的停車提醒共用（Codex 審查 #37）。紅燈、紅色警示燈、危險徵兆，加上燒焦味、煞車軟。「紅色的車」不算。
const URGENT = new RegExp(`紅燈|紅色的?(?:燈|警示)|燈[^，。？?]{0,4}紅|燒焦|焦味|煞車[^，。？?]{0,6}(?:軟|失靈|沒力)|${DANGER}`);
export const isUrgent = (text: string) => URGENT.test(text.replace(TRAFFIC_LIGHT, ""));
